// Package only reviewed decorative media. HTML stays in the server bundle.
import {readFile,writeFile,mkdir,rm,copyFile,realpath} from 'node:fs/promises';
import {resolve,dirname,sep} from 'node:path';
import {fileURLToPath} from 'node:url';

export const HTML_FILES=['order/index.html','admin/preview-v3.html','anketa/mini-preview.html','anketa/ratings.html'];
export const ROOT=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const allowed=/^(?:assets\/(?:visual-v2|order-bot-visuals|account_cards|balance_cards|admin_men)\/[A-Za-z0-9_-]+\.(?:jpg|jpeg|png|webp|mp4)|assets\/[A-Za-z0-9_-]+\.(?:jpg|jpeg|png|webp|mp4)|anketa\/(?:work-main-premium-bg-alt|history-premium-bg|profile-work-premium-bg|cabinet-premium-bg)\.webp)$/;
export function mediaType(path,bytes){
 const ext=path.split('.').at(-1);
 if(['jpg','jpeg'].includes(ext)&&bytes[0]===255&&bytes[1]===216&&bytes[2]===255)return 'image/jpeg';
 if(ext==='png'&&bytes.subarray(0,8).equals(Buffer.from([137,80,78,71,13,10,26,10])))return 'image/png';
 if(ext==='webp'&&bytes.toString('ascii',0,4)==='RIFF'&&bytes.toString('ascii',8,12)==='WEBP')return 'image/webp';
 if(ext==='mp4'&&bytes.toString('ascii',4,8)==='ftyp')return 'video/mp4';
 throw Error('Invalid decorative media format: '+path);
}
export async function staticInputs(root=ROOT){
 const paths=JSON.parse(await readFile(resolve(root,'config/public_media.json'),'utf8'));
 if(!Array.isArray(paths)||!paths.length||paths.length>1000||new Set(paths).size!==paths.length)throw Error('Invalid media manifest');
 const media=[];
 for(const path of paths){
  if(typeof path!=='string'||!allowed.test(path))throw Error('Unapproved media path');
  const source=resolve(root,path);
  if(!source.startsWith(root+sep)||await realpath(source)!==source)throw Error('Media symlink forbidden');
  const bytes=await readFile(source);
  if(!bytes.length||bytes.length>25*1024*1024)throw Error('Media size invalid: '+path);
  media.push({path,source,type:mediaType(path,bytes),size:bytes.length});
 }
 const pages=Object.fromEntries(await Promise.all(HTML_FILES.map(async path=>[path,await readFile(resolve(root,path),'utf8')])));
 for(const html of Object.values(pages))if(/raw\.githubusercontent\.com|cdn\.jsdelivr\.net\/gh\//i.test(html))throw Error('Public GitHub dependency remains in HTML');
 const urls=media.map(x=>'/media/'+x.path);
 const module='// Generated by tools/build_static_files.mjs; HTML is server-only.\n'+
  'export const STATIC_PAGES = '+JSON.stringify(pages)+';\n'+
  'export const PUBLIC_MEDIA_PATHS = '+JSON.stringify(urls)+';\n';
 return {media,pages,module};
}
export async function buildStaticFiles(root=ROOT){
 const inputs=await staticInputs(root);
 const out=resolve(root,'.static-assets');
 await rm(out,{recursive:true,force:true});await mkdir(out,{recursive:true});
 for(const {path,source} of inputs.media){
  const destination=resolve(out,'media',path);
  await mkdir(dirname(destination),{recursive:true});await copyFile(source,destination);
 }
 const generated=resolve(root,'src/generated/static_pages.js');
 await mkdir(dirname(generated),{recursive:true});await writeFile(generated,inputs.module);
 return inputs;
}
if(process.argv[1]&&resolve(process.argv[1])===fileURLToPath(import.meta.url)){
 const result=await buildStaticFiles();
 console.log('Packaged '+Object.keys(result.pages).length+' server-only HTML pages and '+result.media.length+' decorative files');
}
